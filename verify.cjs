const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('script.js', 'utf8');
const fn = source.slice(source.indexOf('function validationMessage'), source.indexOf('function validate('));
const context = { form: { elements: { service: { options: [{ value: '' }, { value: 'Interior remodeling' }] } } } };
vm.createContext(context);
vm.runInContext(fn, context);
const check = context.validationMessage;
for (const email of ['missing-at.com', 'missing@dot', 'a@@b.com', 'a b@c.com', 'a@.com', 'a@b..com', 'a@-b.com', 'a..b@example.com']) assert.ok(check('email', email), email);
for (const email of ['person@example.com', 'first.last+project@example.co.uk']) assert.equal(check('email', email), '');
assert.ok(check('firstName', ' '));
assert.equal(check('firstName', 'José O’Neill'), '');
assert.ok(check('message', 'short'));
assert.ok(check('message', 'a'.repeat(2001)));
assert.equal(check('message', 'Please help repair my leaking roof.'), '');
assert.ok(check('phone', '123'));
assert.ok(check('phone', 'abcdefghij'));
assert.equal(check('phone', '(412) 555-0123'), '');
assert.ok(check('phone', ''));
assert.ok(check('lastName', ''));
assert.equal(check('lastName', 'Li'), '');
assert.ok(check('service', 'invalid'));
assert.equal(check('service', 'Interior remodeling'), '');
const html = fs.readFileSync('Index.html', 'utf8');
for (const match of html.matchAll(/(?:src|href)="(assets\/[^\"]+|styles.css|script.js)"/g)) assert.ok(fs.existsSync(match[1]), match[1]);
for (const match of html.matchAll(/href="#([^\"]+)"/g)) assert.ok(html.includes(`id="${match[1]}"`), match[1]);
console.log('Validation cases, local assets, and anchor links passed.');
